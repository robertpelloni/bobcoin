import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');

const scenarioCatalogPath = path.join(repoRoot, 'testing', 'parity-scenarios.json');
const fragmentCatalogPath = path.join(repoRoot, 'testing', 'parity-fixture-fragments.json');
const outputPath = path.join(repoRoot, 'docs', 'ai', 'testing', 'parity-scenario-matrix.md');

const scenarioCatalog = JSON.parse(fs.readFileSync(scenarioCatalogPath, 'utf8'));
const fragmentCatalog = JSON.parse(fs.readFileSync(fragmentCatalogPath, 'utf8'));

const fragmentsById = new Map(fragmentCatalog.fragments.map((fragment) => [fragment.id, fragment]));

function renderScenarioRow(scenario) {
  return `| ${scenario.id} | ${scenario.accounts} | ${scenario.features.join(', ')} | ${scenario.nodeTest} | ${scenario.goTest} | ${scenario.expectations.join(', ')} |`;
}

function renderFragmentSection(fragmentId) {
  const fragment = fragmentsById.get(fragmentId);
  if (!fragment) {
    return `- ${fragmentId}: missing fragment definition`;
  }
  return `- \`${fragment.id}\` (${fragment.category}) — ${fragment.features.join(', ')}`;
}

const scenarioSections = scenarioCatalog.scenarios.map((scenario) => {
  const fragmentLines = scenario.fragments.map(renderFragmentSection).join('\n');
  return `## ${scenario.id}

- Category: ${scenario.category}
- Accounts: ${scenario.accounts}
- Node replay test: \`${scenario.nodeTest}\`
- Go durable recovery test: \`${scenario.goTest}\`
- Features: ${scenario.features.join(', ')}
- Expectations: ${scenario.expectations.join(', ')}

### Fragment composition
${fragmentLines}
`;
}).join('\n');

const content = `# Parity Scenario Matrix

Generated from:
- \`testing/parity-scenarios.json\`
- \`testing/parity-fixture-fragments.json\`

This document is generated by \`testing/render-parity-matrix.mjs\` and summarizes the active mirrored replay scenarios shared across the Node reference lattice and the Go durable recovery suite.

## Scenario Summary

| Scenario | Accounts | Features | Node Test | Go Test | Expectations |
| --- | ---: | --- | --- | --- | --- |
${scenarioCatalog.scenarios.map(renderScenarioRow).join('\n')}

## Fixture Fragments

${fragmentCatalog.fragments.map((fragment) => `- \`${fragment.id}\` (${fragment.category}) — ${fragment.features.join(', ')}`).join('\n')}

${scenarioSections}`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, content);
console.log(`Wrote parity scenario matrix to ${outputPath}`);
